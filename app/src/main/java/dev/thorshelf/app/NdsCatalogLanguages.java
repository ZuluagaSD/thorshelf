package dev.thorshelf.app;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/** Edition language metadata; a broad sales region alone never implies English. */
final class NdsCatalogLanguages {
    private NdsCatalogLanguages() { }

    static List<String> resolve(String title, String fullName, String explicitLanguages, List<String> regions) {
        if (explicitLanguages != null && !explicitLanguages.trim().isEmpty()) {
            // An invalid explicit list stays unknown instead of borrowing a different edition's data.
            return CatalogLanguages.parse(explicitLanguages);
        }
        List<String> explicit = CatalogLanguages.parse(fullName);
        if (!explicit.isEmpty()) return explicit;
        // Preserve known single-country editions before supplementing broad/unknown regions.
        // Do not expand a Japanese edition to English solely from supplemental data.
        List<String> locale = CatalogLanguages.nds("", fullName, "");
        if (!locale.isEmpty()) return locale;
        List<String> verified = EditionLanguages.VALUES.get(fullName);
        return verified == null ? Collections.emptyList() : verified;
    }

    private static final class EditionLanguages {
        static final Map<String, List<String>> VALUES = verifiedEditions();
        private static Map<String, List<String>> verifiedEditions() {
            Map<String, List<String>> result = new LinkedHashMap<>();
            // Exact USA/Europe editions verified against GameTDB on 2026-10-26:
            // https://www.gametdb.com/DS/IRBO, IRAO, IREO, IRDO (languages EN).
            for (String title : new String[] {"Pokemon - Black Version", "Pokemon - White Version",
                    "Pokemon - Black Version 2", "Pokemon - White Version 2"}) {
                result.put(title + " (USA, Europe) (NDSi Enhanced)", Collections.singletonList("en"));
            }
            // Bundled Java resource generated by scripts/generate_nds_languages.py.
            // Keys retain every edition/revision tag; no fuzzy titles or region-wide guesses.
            try (InputStream input = NdsCatalogLanguages.class.getResourceAsStream("/nds-languages.tsv")) {
                if (input != null) {
                    try (BufferedReader reader = new BufferedReader(new InputStreamReader(input, StandardCharsets.UTF_8))) {
                        String line;
                        int rows = 0, characters = 0;
                        while ((line = reader.readLine()) != null) {
                            characters += line.length();
                            if (++rows > 10000 || characters > 1024 * 1024) break;
                            if (line.startsWith("#") || line.length() > 1152) continue;
                            String[] fields = line.split("\t", -1);
                            if (fields.length != 3 || fields[0].isEmpty() || !fields[2].matches("[A-Z0-9]{4}")) continue;
                            List<String> codes = CatalogLanguages.parse(fields[1]);
                            if (!codes.isEmpty()) result.put(fields[0], codes);
                        }
                    }
                }
            } catch (IOException ignored) {
                // Explicit source fields and the small verified fallback still work offline.
            }
            return Collections.unmodifiableMap(result);
        }
    }
}
